import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import {connectDB} from './config/db.js';
import api from './routes/api.js';
const app=express();
app.use(helmet());app.use(cors({origin:(process.env.CLIENT_ORIGIN||'http://localhost:5173').split(','),credentials:false}));app.use(express.json({limit:'2mb'}));app.use(morgan('dev'));app.use('/api/auth',rateLimit({windowMs:15*60*1000,max:30,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(req,res)=>res.json({status:'ok',service:'CampusCore API',time:new Date().toISOString()}));
app.use('/api',api);
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:process.env.NODE_ENV==='production'?'Internal server error':err.message});});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`CampusCore API running at http://localhost:${port}`))).catch(e=>{console.error('Database connection failed:',e.message);process.exit(1);});
